#Python Comparison Exercise
a =89
b =-90
result = a > b #Greater than comparison Exercise
print("result of",a, ">",b,"is",result)

result = a < b #Less than comparison Exercise
print("result of",a, "<",b,"is",result)
result = a >= b #Greater than or equal to comparison Exercise
print("result of",a, ">=",b,"is",result)
result = a <= b #Less than or equal to comparison Exercise
print("result of",a, "<=",b,"is",result)